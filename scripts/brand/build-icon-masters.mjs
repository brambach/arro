#!/usr/bin/env node
/**
 * Writes the icon's SVG masters to assets/brand/ from the art in stone-icon.mjs
 * (candidate E in design/brand/icon-explorations.png). Run it when the art
 * changes, then `node scripts/generate-icons.mjs` to render every size.
 *
 *   node scripts/brand/build-icon-masters.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { stoneGeometry, stoneIcon, stoneLocalPath } from './stone-icon.mjs';
import { repoRoot } from '../lib/load-theme.mjs';

const dir = join(repoRoot, 'assets/brand');
mkdirSync(dir, { recursive: true });

const masters = {
  /** The app icon, light, over 60 px: the stone on birch, tapered steam, texture. */
  'icon.svg': stoneIcon(),
  /** iOS dark appearance: the stone on char, the heat a little brighter. */
  'icon-dark.svg': stoneIcon({ tone: 'dark' }),
  /** iOS tinted appearance: one tone on transparent; iOS applies the tint. */
  'icon-tinted.svg': stoneIcon({ tone: 'tinted', background: false }),
  /** 21 to 60 px: a bigger stone, two short bold wisps, no texture. */
  'icon-small.svg': stoneIcon({ detail: 'small' }),
  /** 20 px and under: the biggest stone, no wisps. */
  'icon-tiny.svg': stoneIcon({ detail: 'tiny' }),
  /** The favicon: the same as tiny. */
  'favicon.svg': stoneIcon({ detail: 'tiny' }),
  /** Android adaptive layers: the art inside the 66% safe zone, and the birch behind it. */
  'android-foreground.svg': stoneIcon({ background: false, scale: 0.66 }),
  'android-background.svg': stoneIcon({ art: false }),
  'android-monochrome.svg': stoneIcon({ tone: 'tinted', background: false, scale: 0.66 }),
  /** Saunafam Plus app icons (Me, App icon): the same stone at night, on cedar boards, by the lake. */
  'icon-night.svg': stoneIcon({ scene: 'night' }),
  'icon-cedar.svg': stoneIcon({ scene: 'cedar' }),
  'icon-lake.svg': stoneIcon({ scene: 'lake' }),
};

for (const [name, svg] of Object.entries(masters)) {
  writeFileSync(join(dir, name), svg + '\n');
  console.log(`wrote assets/brand/${name}`);
}

// The same stone for the app's own mark (the splash), so they never drift apart.
const ts = [
  "// Generated by scripts/brand/build-icon-masters.mjs. Don't edit by hand; run that instead.",
  "// The icon's stone (scripts/brand/stone-icon.mjs) in its own frame, centered on 0, 0.",
  '',
  `export const stonePath = '${stoneLocalPath}';`,
  '',
  `export const stoneGeometry = ${JSON.stringify(stoneGeometry, null, 2).replace(/"(\w+)":/g, '$1:')} as const;`,
  '',
].join('\n');
writeFileSync(join(repoRoot, 'src/components/brand/stonePath.ts'), ts);
console.log('wrote src/components/brand/stonePath.ts');
