#!/usr/bin/env node
/**
 * Writes the icon's SVG masters to assets/brand/ from the art in icon-art.mjs
 * (the pick, D, in design/brand/icon-explorations.png). Run it when the art
 * changes, then `node scripts/generate-icons.mjs` to render every size.
 *
 *   node scripts/brand/build-icon-masters.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { chosen, icon, stones } from './icon-art.mjs';
import { repoRoot } from '../lib/load-theme.mjs';

const dir = join(repoRoot, 'assets/brand');
mkdirSync(dir, { recursive: true });

const masters = {
  /** The app icon, light: the stone on birch. */
  'icon.svg': icon({ ...chosen }),
  /** iOS dark appearance: the stone on char, the heat a little brighter. */
  'icon-dark.svg': icon({ ...chosen, tone: 'dark' }),
  /** iOS tinted appearance: one tone on transparent; iOS applies the tint. */
  'icon-tinted.svg': icon({ ...chosen, tone: 'tinted', background: false }),
  /** 40 px and under: no texture, bolder wisps. */
  'icon-small.svg': icon({ ...chosen, detail: 'small' }),
  /** The favicon: no wisps, a bigger stone, bolder heat. */
  'favicon.svg': icon({ ...chosen, detail: 'favicon' }),
  /** Android adaptive layers: the art inside the 66% safe zone, and the birch behind it. */
  'android-foreground.svg': icon({ ...chosen, artScale: chosen.artScale * 0.66, background: false }),
  'android-background.svg': icon({ ...chosen, art: false }),
  'android-monochrome.svg': icon({ ...chosen, tone: 'tinted', background: false, artScale: chosen.artScale * 0.66 }),
};

for (const [name, svg] of Object.entries(masters)) {
  writeFileSync(join(dir, name), svg + '\n');
  console.log(`wrote assets/brand/${name}`);
}

// The same outline for the app's own stone mark (the splash), so they never drift apart.
const ts = [
  '// Generated by scripts/brand/build-icon-masters.mjs. Don\'t edit by hand; run that instead.',
  '// The icon\'s stone outline on its 1024 grid (scripts/brand/icon-art.mjs, the pick).',
  '',
  `export const stonePath = '${stones[chosen.stone]}';`,
  '',
].join('\n');
writeFileSync(join(repoRoot, 'src/components/brand/stonePath.ts'), ts);
console.log('wrote src/components/brand/stonePath.ts');
